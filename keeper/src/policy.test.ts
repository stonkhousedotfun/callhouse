/**
 * The strike picker and the sizer, pinned integer for integer against contracts/src/Policy.sol.
 *
 * WHY THIS FILE EXISTS: every number policy.ts produces is re-derived on chain by the vault, and
 * the vault's answer wins. A picker that is one base unit under the premium floor, or one rung
 * outside the band, is a `PremiumBelowMinimum` or `StrikeBelowBand` revert at 20:00 UTC on a
 * Friday — the keeper's simulation catches it, but the week is still unwritten. These tests pin
 * the maths to the values the contracts compute, using the real cycle-1 NVDA ladder and the real
 * Chainlink print from 2026-09-12 so the fixtures are numbers that actually occurred.
 *
 * The fee-split vectors are generated by the SAME linear congruential generator, seed and loop as
 * contracts/test/unit/SplitDiff.t.sol. Change one side and the other must change with it.
 *
 * DELIBERATELY ABSENT: no RPC and no HTTP. `readLastFill` is injected through the seam on
 * PickInput, so nothing here dials Overcall, and the RPC in the environment is a discard port.
 */
