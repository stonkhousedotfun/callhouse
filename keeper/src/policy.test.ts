test('the ceiling clears Policy.checkPremium for every size; one unit below misses at n = 2', () => {
  // Policy.checkPremium: gross >= floor(spot * n * minPremiumBps / 10000), with gross = unit * n.
  const onChainMin = (n: bigint) => (SPOT * n * LAUNCH.minPremiumBps) / BPS;
  const ceilUnit = minUnitPrice6(SPOT, LAUNCH);
  const floorUnit = ceilUnit - 1n;

  for (let n = 1n; n <= 50n; n += 1n) {
    assert.ok(ceilUnit * n >= onChainMin(n), `ceiling unit clears the floor at n=${n}`);
  }
  // n = 1 happens to pass with the floored unit (873191 >= floor(873191.736) = 873191)...
  assert.ok(floorUnit * 1n >= onChainMin(1n));
  // ...and n = 2 is the first size where it reverts PremiumBelowMinimum: 1746382 < 1746383.
  assert.equal(floorUnit * 2n, 1_746_382n);
  assert.equal(onChainMin(2n), 1_746_383n);
  assert.ok(floorUnit * 2n < onChainMin(2n));
});

test('pickWrite prices from the floor, lifts to a CLAMPED last fill, never below the listable minimum, never above the strike', async () => {
  const floor = await pick();
  assert.ok(floor.ok);
  assert.equal(floor.unitPrice6, 873_192n);
  assert.equal(floor.priceSource, 'policy-floor');
  assert.equal(floor.contracts, 23n);
  assert.equal(floor.gross6, 873_192n * 23n);
  assert.equal(floor.toVault6 + floor.toOvercall6, floor.gross6);
  assert.equal(floor.endTime, CYCLE.exerciseTimestamp, 'the order ends at book close, not expiry');

  // A last fill within LAST_FILL_MAX_LIFT of the floor sets the ask.
  const lifted = await pick({ readLastFill: async () => 2_000_000n });
  assert.ok(lifted.ok);
  assert.equal(lifted.unitPrice6, 2_000_000n);
  assert.equal(lifted.priceSource, 'last-fill');

  // A last fill BEYOND the cap is clamped to 3x the floor, not obeyed: anyone can self-fill
  // one contract at an absurd price for the cost of the 5% fee, and an unclamped lift would
  // price the whole vault at the attacker's number and guarantee an unfilled week.
  assert.equal(LAST_FILL_MAX_LIFT, 3n);
  const capped = await pick({ readLastFill: async () => 4_000_000n });
  assert.ok(capped.ok);
  assert.equal(capped.unitPrice6, 873_192n * 3n);
  assert.equal(capped.priceSource, 'last-fill');
  const absurd = await pick({ readLastFill: async () => 300_000_000n });
  assert.ok(absurd.ok, 'clamped, not refused: 300 USDG on a 218 USDG spot is a fake print, not a price');
  assert.equal(absurd.unitPrice6, 873_192n * 3n);

  // A last fill below the floor is ignored: the floor is a floor.
  const low = await pick({ readLastFill: async () => 500_000n });
  assert.ok(low.ok);
  assert.equal(low.unitPrice6, 873_192n);
  assert.equal(low.priceSource, 'policy-floor');

  // A microscopic spot puts the floor under 20 base units; the ask is lifted to 20 so
  // Overcall's 5% does not round to a zero-amount consideration item.
  const tiny = await pick({
    spotUsdg6: 1_000n,
    rungs: rungs({ 0: { strikeUsdg6: 1_050n } }), // 5% OTM at a $0.001 spot
  });
  assert.ok(tiny.ok);
  assert.equal(tiny.unitPrice6, MIN_LISTABLE_UNIT_PRICE_6);
  assert.equal(MIN_LISTABLE_UNIT_PRICE_6, 20n);

  // An ask above the strike is a fat finger the vault would reject: refused, not clamped.
  // (Reachable today only through the manual override — the last-fill cap keeps the book's
  // signal far under any in-band strike at the launch policy.)
  const tooHigh = await pick({ unitPriceOverride6: 226_000_001n });
  assert.equal(tooHigh.ok, false);
  if (!tooHigh.ok) assert.equal(tooHigh.reason, 'premium-above-strike');
});

