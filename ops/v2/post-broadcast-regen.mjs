/* ---------------------------------------------------------------------------------------------- */
/*  enumeration: the tree names its generators                                                     */
/* ---------------------------------------------------------------------------------------------- */

/** `GENERATED by <generator>[ … from <input>]` anywhere in the first lines of a file. Case-insensitive
 *  ("Generated by" is the reward-epochs form). Trailing punctuation a comment sentence adds is dropped. */
// The input is the first `from <path>` after the generator, on the same line; a path has a `/` or a
// `.`, so "from the run" names nothing.
const HEADER = /generated by\s+`?([A-Za-z0-9_./-]+)`?(?:[^\n]*?\bfrom\s+([A-Za-z0-9_-]*[./][A-Za-z0-9_./-]*))?/i;

export function parseHeader(head) {
  const m = HEADER.exec(head);
  if (!m) return null;
  const generator = m[1].replace(/[.;:,]+$/, "");
  const from = m[2] ? m[2].replace(/[.;:,]+$/, "") : null;
  return { generator, from };
}

/** Nearest ancestor directory of `file` (repo-relative) that holds a package.json, or "" for the root. */
export function packageRootOf(file, exists) {
  let dir = path.posix.dirname(file);
  while (dir && dir !== ".") {
    if (exists(path.posix.join(dir, "package.json"))) return dir;
    dir = path.posix.dirname(dir);
  }
  return "";
}

/**
 * A header names its generator either repository-relative (`web/scripts/gen-markets.mjs`) or relative
 * to the output's package (`scripts/gen-abis.mjs` inside web/, indexer/ or keeper/). Resolve to the
 * repository-relative path, or null when neither exists.
 */
export function resolveGenerator(file, name, exists) {
  if (exists(name)) return name;
  const pkg = packageRootOf(file, exists);
  const inPackage = pkg ? path.posix.join(pkg, name) : null;
  if (inPackage && exists(inPackage)) return inPackage;
  return null;
}

const HEAD_BYTES = 1200;
const BINARY = /\.(png|jpe?g|gif|svg|ico|woff2?|ttf|otf|pdf|zip|gz|wasm)$/i;

/**
 * Walk `files` (repository-relative, tracked) and attribute every generated one to a recipe.
 * `readHead(file)` returns the first bytes of a file; `exists(path)` answers repository-relative.
 * Pure: no process, no git. Returns { recipes, excluded, refusals } where
 *   recipes[generator] = { ...RECIPES[generator], generator, outputs: [{ file, from }] }
 */
export function enumerate(files, readHead, exists, recipes = RECIPES) {
  const found = new Map(); // generator -> outputs
  const refusals = [];
  const generatedPattern = /\.generated\.[a-z]+$/i;
  const attributedHeaderless = new Map();
  for (const [gen, r] of Object.entries(recipes)) for (const f of r.headerless ?? []) attributedHeaderless.set(f, gen);

  for (const file of files) {
    if (BINARY.test(file)) continue;
    // A recipe's own source mentions the convention; a generator is not its own output.
    if (file in recipes) continue;
    const head = readHead(file);
    const h = head === null ? null : parseHeader(head);
    let generator = null;
    if (h) {
      generator = resolveGenerator(file, h.generator, exists);
      if (generator === null) {
        refusals.push(`${file}: header names generator '${h.generator}', which exists neither at the repository root nor in the file's package`);
        continue;
      }
    } else if (attributedHeaderless.has(file)) {
      generator = attributedHeaderless.get(file);
    } else if (generatedPattern.test(file)) {
      refusals.push(`${file}: a *.generated.* file with no 'GENERATED by' header and no recipe that names it (add it to the generator's recipe 'headerless' list once you know which script writes it)`);
      continue;
    } else continue;

    if (!(generator in recipes)) {
      refusals.push(`${file}: generated by '${generator}', which has no recipe here — a generator landed without this runner learning how to run it`);
      continue;
    }
    if (!found.has(generator)) found.set(generator, []);
    found.get(generator).push({ file, from: h?.from ?? null });
  }

  // Every recipe that claims to own tracked outputs must have found at least one, or it is stale.
  const out = {};
  const excluded = [];
  for (const [gen, r] of Object.entries(recipes)) {
    if (r.skip) {
      excluded.push({ generator: gen, reason: r.skip, outputs: found.get(gen) ?? [] });
      continue;
    }
    const outputs = found.get(gen) ?? [];
    if (outputs.length === 0 && !r.external && r.role !== "registry") {
      refusals.push(`recipe '${gen}' has no discovered output in the tree: either its outputs lost their header or the recipe is stale`);
    }
    if (!exists(gen)) refusals.push(`recipe '${gen}' names a generator that does not exist`);
    out[gen] = { ...r, generator: gen, outputs };
  }
  return { recipes: out, excluded, refusals };
}

