function git(args, cwd = REPO) {
  const r = spawnSync("git", args, { cwd, encoding: "utf8" });
  if (r.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${r.stderr}`);
  return r.stdout;
}

/** Tracked, non-binary files, with a lazy head reader and an existence check, from the real tree. */
function treeView() {
  const files = git(["ls-files", "-z"]).split("\0").filter(Boolean);
  const readHead = (file) => {
    const abs = path.join(REPO, file);
    let st;
    try { st = statSync(abs); } catch { return null; }
    if (!st.isFile()) return null;
    try {
      // Only the first bytes: generated files can be megabytes and the header is on top.
      const buf = readFileSync(abs);
      return buf.subarray(0, HEAD_BYTES).toString("utf8");
    } catch { return null; }
  };
  const exists = (rel) => existsSync(path.join(REPO, rel));
  return { files, readHead, exists };
}

function substitute(argv, vars) {
  return argv.map((a) => a.replace(/\{(\w+)\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`recipe placeholder {${k}} has no value`);
    return vars[k];
  }));
}

function run(argv, cwd) {
  const started = Date.now();
  const r = spawnSync(argv[0], argv.slice(1), { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  return { status: r.status, signal: r.signal, stdout: r.stdout ?? "", stderr: r.stderr ?? "", ms: Date.now() - started };
}

/** `git diff --numstat` over the given paths plus untracked files under their directories. */
function changed(paths) {
  if (paths.length === 0) return [];
  const rows = [];
  const numstat = git(["diff", "--numstat", "--", ...paths]);
  for (const line of numstat.split("\n").filter(Boolean)) {
    const [add, del, file] = line.split("\t");
    rows.push({ file, add: add === "-" ? "bin" : Number(add), del: del === "-" ? "bin" : Number(del), state: "modified" });
  }
  const dirs = [...new Set(paths.map((p) => path.posix.dirname(p)))];
  const untracked = git(["ls-files", "--others", "--exclude-standard", "--", ...dirs]);
  for (const file of untracked.split("\n").filter(Boolean)) {
    const lines = readFileSync(path.join(REPO, file), "utf8").split("\n").length - 1;
    rows.push({ file, add: lines, del: 0, state: "new" });
  }
  return rows;
}

function tail(text, n = 12) {
  const lines = text.trimEnd().split("\n");
  return (lines.length > n ? ["…", ...lines.slice(-n)] : lines).map((l) => `      ${l}`).join("\n");
}

function parseArgs(argv) {
  const opts = { registry: CANONICAL_REGISTRY, docsOut: null, docsDir: null, checkOnly: false, registryCheck: true, only: null, list: false };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    const value = () => {
      const v = argv[++i];
      if (v === undefined || v.startsWith("--")) usage(`${a} needs a value`);
      return v;
    };
    if (a === "--registry") opts.registry = path.resolve(value());
    else if (a === "--docs-out") opts.docsOut = path.resolve(value());
    else if (a === "--docs-dir") opts.docsDir = path.resolve(value());
    else if (a === "--check") opts.checkOnly = true;
    else if (a === "--no-registry-check") opts.registryCheck = false;
    else if (a === "--only") opts.only = new Set(value().split(",").filter(Boolean));
    else if (a === "--list") opts.list = true;
    else if (a === "-h" || a === "--help") usage();
    else usage(`unknown argument: ${a}`);
  }
  return opts;
}

/**
 * The callhouse-docs checkout, read only, for the diff line and for `--check`: beside the main checkout
 * (`../callhouse-docs`) or, when this is a worktree under `wt/`, beside the workspace (`../../`). Never
 * written. Null when neither exists.
 */
function findDocsCheckout() {
  for (const candidate of [path.resolve(REPO, "..", "callhouse-docs"), path.resolve(REPO, "..", "..", "callhouse-docs")]) {
    if (existsSync(path.join(candidate, "product", "markets.md"))) return candidate;
  }
  return null;
}

function usage(message) {
  if (message) process.stderr.write(`post-broadcast-regen: ${message}\n`);
  process.stderr.write("usage: node ops/v2/post-broadcast-regen.mjs [--registry FILE] [--docs-out DIR] [--docs-dir DIR] [--check] [--no-registry-check] [--only gen,gen] [--list]\n");
  process.exit(message ? 2 : 0);
}

export function main(argv) {
  const opts = parseArgs(argv);
  if (!existsSync(opts.registry)) usage(`registry not found: ${opts.registry}`);
  const rehearsal = path.resolve(opts.registry) !== CANONICAL_REGISTRY;
  const registryLabel = path.relative(REPO, opts.registry).startsWith("..") ? opts.registry : path.relative(REPO, opts.registry);

  const { files, readHead, exists } = treeView();
  const { recipes, excluded, refusals } = enumerate(files, readHead, exists);

  console.log(`post-broadcast-regen: registry ${registryLabel}${rehearsal ? "  (REHEARSAL: not the canonical ops/markets/tier1.json)" : ""}`);
  console.log(`enumerated ${files.length} tracked files: ${Object.keys(recipes).length} recipes, ${Object.values(recipes).reduce((n, r) => n + r.outputs.length, 0)} generated outputs attributed, ${excluded.length} generators listed and not re-run`);
  for (const r of Object.values(recipes)) {
    const froms = [...new Set(r.outputs.map((o) => o.from).filter(Boolean))];
    console.log(`  ${r.generator.padEnd(40)} ${String(r.outputs.length).padStart(3)} output(s)  input: ${r.input}${froms.length ? `  headers say from: ${froms.join(", ")}` : ""}`);
  }
  for (const e of excluded) console.log(`  ${e.generator.padEnd(40)} not re-run: ${e.reason}`);
  if (refusals.length) {
    console.error(`\nREFUSED before running anything (${refusals.length}):`);
    for (const r of refusals) console.error(`  - ${r}`);
    return 1;
  }
  if (opts.list) return 0;

  const docsOut = opts.docsOut ?? mkdtempSync(path.join(tmpdir(), "callhouse-docs-render-"));
  const docsSibling = opts.docsDir ?? findDocsCheckout();
  const vars = { registry: opts.registry, docsOut, docsSibling: docsSibling ?? "" };
  const order = Object.values(recipes).sort((a, b) => rank(a) - rank(b) || a.generator.localeCompare(b.generator));
  const results = [];
  let failed = 0;
  let rehearsalWrites = 0;

  for (const r of order) {
    if (opts.only && !opts.only.has(r.generator)) continue;
    if (r.role === "registry" && !opts.registryCheck) {
      console.log(`\n== ${r.generator}: skipped (--no-registry-check)`);
      results.push({ generator: r.generator, status: "skipped" });
      continue;
    }
    if (rehearsal && r.registryFlag === false) {
      console.log(`\n== ${r.generator}: skipped — it reads the canonical registry only and this is a rehearsal against ${registryLabel}`);
      results.push({ generator: r.generator, status: "skipped (rehearsal)" });
      continue;
    }
    const cwd = path.join(REPO, r.cwd);
    const outputs = r.outputs.map((o) => o.file);
    console.log(`\n== ${r.generator}  (${r.input})`);

    if (!opts.checkOnly && r.write) {
      const argv = substitute(r.write, vars);
      const w = run(argv, cwd);
      console.log(`   write  ${argv.join(" ")}  → rc=${w.status ?? w.signal} ${w.ms} ms`);
      if (w.status !== 0) {
        console.log(tail(w.stderr || w.stdout));
        results.push({ generator: r.generator, status: `WRITE FAILED rc=${w.status ?? w.signal}` });
        failed += 1;
        continue;
      }
      if (rehearsal && r.registryFlag) rehearsalWrites += 1;
    }
    if (opts.checkOnly && r.external) {
      if (!r.checkOnly || docsSibling === null) {
        console.log("   skipped: --check has no render to compare and no callhouse-docs checkout beside this repository (pass --docs-dir)");
        results.push({ generator: r.generator, status: "skipped (no docs checkout)" });
        continue;
      }
    }
    const argv = substitute(opts.checkOnly && r.external ? r.checkOnly : r.check, vars);
    const c = run(argv, cwd);
    console.log(`   check  ${argv.join(" ")}  → rc=${c.status ?? c.signal} ${c.ms} ms`);
    if (c.status !== 0) {
      console.log(tail(c.stderr || c.stdout));
      results.push({ generator: r.generator, status: `CHECK FAILED rc=${c.status ?? c.signal}` });
      failed += 1;
      continue;
    }
    if (r.external) {
      if (opts.checkOnly) {
        console.log(`   in sync with ${docsSibling} (read only)`);
        results.push({ generator: r.generator, status: "ok", changed: [] });
        continue;
      }
      console.log(`   wrote  ${path.join(docsOut, "product", "markets.md")}`);
      const sibling = docsSibling === null ? null : path.join(docsSibling, "product", "markets.md");
      if (sibling !== null && existsSync(sibling)) {
        const d = spawnSync("diff", ["--stat", sibling, path.join(docsOut, "product", "markets.md")], { encoding: "utf8" });
        console.log(`   vs ${sibling} (read only): ${d.status === 0 ? "identical" : (d.stdout.trim().split("\n").pop() || "differs")}`);
      }
      results.push({ generator: r.generator, status: "ok", changed: [] });
      continue;
    }
    const rows = opts.checkOnly ? [] : changed(outputs);
    if (rows.length === 0) console.log(`   ${opts.checkOnly ? "in sync" : "no output changed"}`);
    for (const row of rows) console.log(`   ${row.state.padEnd(8)} +${row.add} -${row.del}  ${row.file}`);
    results.push({ generator: r.generator, status: "ok", changed: rows });
  }

  console.log("\nsummary");
  for (const s of results) {
    const n = s.changed ? `${s.changed.length} file(s) changed, +${sum(s.changed, "add")} -${sum(s.changed, "del")}` : "";
    console.log(`  ${s.status.padEnd(22)} ${s.generator.padEnd(40)} ${n}`);
  }
  console.log(`docs render: ${docsOut}`);
  if (rehearsalWrites > 0) {
    console.log(`\nREHEARSAL: ${rehearsalWrites} generator(s) wrote outputs marked "(REHEARSAL, do not commit)" from ${registryLabel}. Restore them with \`git checkout -- <paths>\` before committing anything.`);
  }
  if (failed > 0) {
    console.error(`\nREFUSED: ${failed} step(s) failed; nothing was committed. The tree holds each generator's output for inspection.`);
    return 1;
  }
  console.log(opts.checkOnly ? "\nall generators in sync with the registry" : "\nall generators wrote and re-checked green; review `git diff --stat` and commit with the registry");
  return 0;
}

const sum = (rows, k) => rows.reduce((n, r) => n + (typeof r[k] === "number" ? r[k] : 0), 0);
/** Registry proof first, then everything rendered from the registry, then the fixed-input projections, docs last. */
function rank(r) {
  if (r.role === "registry") return 0;
  if (r.external) return 3;
  return r.input === "registry" ? 1 : 2;
}

