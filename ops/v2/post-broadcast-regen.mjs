#!/usr/bin/env node
/* -------------------------------------------------------------------------------------------------
 * ops/v2/post-broadcast-regen.mjs — one command that, after the v8 broadcast has written the deployed
 * addresses back into ops/markets/tier1.json, regenerates EVERY generated artefact this repository
 * derives from it (and the ABI/roles projections beside them), re-runs each generator's own
 * `--check` against what it just wrote, and prints what changed. Launch night is:
 *
 *   node ops/v2/post-broadcast-regen.mjs --registry ops/markets/tier1.json
 *   git diff --stat            # review, then commit the regenerated files with the written-back registry
 *
 * Nothing here is typed by hand. The generators are ENUMERATED FROM THE TREE: every tracked file whose
 * header says `GENERATED by <generator> [from <input>]` (the repository convention — see any file under
 * web/lib/abi/v2, indexer/lib/v2, ops/v2/env, ops/keeper/markets) names the script that owns it, and a
 * header-less `*.generated.json` is attributed to the one generator script whose source names it. That
 * discovered set is joined to the RECIPES table below (how to invoke each generator: cwd, flags, which
 * input it reads), and the run REFUSES when
 *
 *   - a generated file names a generator this table does not know (a new generator landed without a
 *     recipe: the drift shape a hand-typed list would hide),
 *   - a generated file names a generator that does not exist at that path,
 *   - a `*.generated.*` file has no header and no generator source names it,
 *   - a recipe has no discovered output at all (the table is stale), or
 *   - any generator's `--check` exits non-zero AFTER its write (it disagrees with itself; nothing is
 *     committed by this script, so the tree is left for inspection).
 *
 * Generators whose header appears in the tree but which are NOT re-run (one-shot recon probes, the
 * rehearsal report, the registry builder that is the SOURCE rather than a consumer) are listed with
 * the reason, so the enumeration is still complete: every generator the tree names is accounted for.
 *
 * `--registry FILE` other than ops/markets/tier1.json is a REHEARSAL: the generators that accept
 * `--registry` run against that file and mark their output "(REHEARSAL, do not commit)", the ones that
 * read the canonical path only (render-docs) are skipped by name, and the run ends with a loud
 * do-not-commit line. To drill the real launch-night flow, copy the written-back registry OVER
 * ops/markets/tier1.json in a scratch worktree and run with the canonical path.
 *
 * render-docs never touches ../callhouse-docs from here: it renders to `--docs-out DIR` (default: a
 * fresh directory under the system temp dir) and the path is printed; publishing the docs repo stays
 * owner-gated. If the sibling docs checkout exists, a read-only `diff --stat` against it is printed.
 *
 *   node ops/v2/post-broadcast-regen.mjs [--registry FILE] [--docs-out DIR] [--docs-dir DIR] [--check]
 *                                        [--no-registry-check] [--only gen1,gen2] [--list]
 *
 *   --check              run only each generator's --check (write nothing); exit 1 on any drift. For
 *                        render-docs this compares the callhouse-docs checkout's page (read only)
 *   --docs-dir DIR       the callhouse-docs checkout to diff/check against (default: found beside the
 *                        main checkout or the workspace); it is read, never written
 *   --no-registry-check  skip `build-markets.mjs --check` (it reads the chain and the feed directory,
 *                        ~90 s; the default keeps it because launch night wants the registry proven
 *                        before anything is rendered from it)
 *   --only a,b           run only these recipes (by generator path); the enumeration still runs in full
 *   --list               print the enumeration (recipes, outputs, exclusions, refusals) and exit
 *
 * Exit codes: 0 all steps green; 1 a step or the enumeration refused; 2 bad arguments.
 * ------------------------------------------------------------------------------------------------- */
