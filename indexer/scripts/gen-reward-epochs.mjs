#!/usr/bin/env node
/** Project committed reward files into the indexer image; proofs remain in the published source. */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..", "..");
const OUT = join(REPO, "indexer", "lib", "v2", "rewardEpochFiles.generated.ts");
const SOURCES = [{ program: "maker", directory: join(REPO, "ops", "maker-epochs") }];
const UINT = /^(0|[1-9]\d*)$/;
const ROOT = /^0x[0-9a-fA-F]{64}$/;
const ADDRESS = /^0x[0-9a-fA-F]{40}$/;

function project(program, path, expectedEpoch) {
  const value = JSON.parse(readFileSync(path, "utf8"));
  if (!value || typeof value !== "object" || Array.isArray(value) ||
      value.epoch !== expectedEpoch || !ROOT.test(value.root) || !UINT.test(value.total) ||
      !Array.isArray(value.entries)) {
    throw new Error(`invalid reward epoch file ${path}`);
  }
  const entries = value.entries.map((entry, index) => {
    if (!entry || typeof entry !== "object" || Array.isArray(entry) ||
        entry.index !== index || !ADDRESS.test(entry.account) || !UINT.test(entry.amount) ||
        !Array.isArray(entry.proof)) {
      throw new Error(`invalid reward entry ${path}#${index}`);
    }
    return { index, account: entry.account, amount: entry.amount };
  });
  return { program, epoch: value.epoch, root: value.root, total: value.total, entries };
}

const files = SOURCES.flatMap(({ program, directory }) => readdirSync(directory)
  .filter((name) => /^\d+\.json$/.test(name))
  .map((name) => project(program, join(directory, name), Number(name.slice(0, -5)))))
  .sort((left, right) => left.program.localeCompare(right.program) || left.epoch - right.epoch);

const body = `/** Generated by scripts/gen-reward-epochs.mjs; do not edit. */
export type RewardEpochProjection = {
  program: string;
  epoch: number;
  root: \`0x\${string}\`;
  total: string;
  entries: readonly { index: number; account: string; amount: string }[];
};

export const REWARD_EPOCH_FILES = ${JSON.stringify(files, null, 2)} as const satisfies readonly RewardEpochProjection[];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* reported as drift below */ }
  if (current !== body) {
    console.error("reward epoch projection drifted; run: node indexer/scripts/gen-reward-epochs.mjs");
    process.exit(1);
  }
  console.log(`reward epoch projection OK — ${files.length} file(s)`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${files.length} reward epoch projection(s)`);
}
